/**
 * 根据ID获取卦象数据
 */
export function getHexagramById(id: number): HexagramBasicData | undefined {
  return hexagrams.find(h => h.id === id)
}

/**
 * 根据名称获取卦象数据
 */
export function getHexagramByName(name: string): HexagramBasicData | undefined {
  return hexagrams.find(h => h.name === name || h.fullName === name)
}

/**
 * 根据上下卦获取卦象数据
 */
export function getHexagramByTrigrams(upper: string, lower: string): HexagramBasicData | undefined {
  return hexagrams.find(h => h.upperTrigram === upper && h.lowerTrigram === lower)
}
